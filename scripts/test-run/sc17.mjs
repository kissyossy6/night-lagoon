import { open, scenario, openEditor, wait, ROOT } from './lib.mjs';
import { spawn } from 'node:child_process';
import { readdirSync, unlinkSync } from 'node:fs';
const S = scenario(17, 'Art-Net で送って受ける');
const { browser, page, errors } = await open({ w: 1440, h: 900 });
const dir = ROOT + 'exports/control/';
const before = new Set(readdirSync(dir));
await openEditor(page, 'fresh', 'lagoon');
// make a recording of 10-20 s at 40 fps to compare with
await page.click('#cx-btn'); await page.click('#cx-pop button[data-id="dmx-record"]'); await wait(400);
await page.check('input[name="cx-range"][value="part"]'); await page.fill('#cx-from', '10'); await page.fill('#cx-to', '20'); await page.selectOption('#cx-fps', '40');
await page.dispatchEvent('#cx-form', 'input'); await wait(300);
await page.click('#cx-go');
await page.waitForFunction(() => !document.getElementById('cx-done').hidden || !document.getElementById('cx-error').hidden, null, { timeout: 240000 });
const rec = readdirSync(dir).filter((f) => !before.has(f));
await page.click('#cx-cancel');
S.rec('17.前準備', rec.length === 1 ? 'info' : 'fail', `比べる用の DMX の記録（10〜20 秒・40 fps）を書いた: ${rec.join(',')}`);
const recPath = dir + rec[0];
// listener
const lines = [];
const t0 = Date.now();
const child = spawn('node', ['scripts/artnet-listen.mjs', `--compare=${recPath}`, '--seconds=30'], { cwd: ROOT });
child.stdout.on('data', (d) => d.toString().split('\n').filter(Boolean).forEach((l) => lines.push([((Date.now() - t0) / 1000).toFixed(1), l])));
child.stderr.on('data', (d) => lines.push(['err', d.toString()]));
let exitCode = null; child.on('exit', (c) => (exitCode = c));
await wait(1500);
await page.evaluate(() => window.__editor.transport.seek(12));
await wait(500);
await page.click('#cx-btn'); await page.click('#cx-pop button[data-act="artnet"]'); await wait(500);
const dlg = { host: await page.inputValue('#an-host'), port: await page.inputValue('#an-port'), fps: await page.textContent('#an-fps'), text: (await page.textContent('#an h2').catch(() => '')) };
const shotDlg = await S.shot(page, '1-artnet-dialog');
S.rec('17.1', dlg.host === '127.0.0.1' && dlg.port === '6454' ? 'pass' : 'fail', `「書き出し ▾」→「Art-Net で送る…」が開いた。画面「${dlg.text}」、送り先 IP ${dlg.host}、ポート ${dlg.port}（初めの値）、コマ数の表示「${dlg.fps}」`, '', [shotDlg]);
await page.click('#an-go'); await wait(2500);
const chip = await page.evaluate(() => ({ vis: !document.getElementById('an-chip').hidden, txt: document.getElementById('an-chip').textContent, state: document.getElementById('an-state').textContent }));
const shotSend = await S.shot(page, '2-sending');
await page.click('#an-close'); await wait(500);
const inSet1 = lines.filter(([t, l]) => /U1/.test(l)).length;
S.rec('17.2', chip.vis && chip.txt.includes('Art-Net 送信中') && inSet1 > 0 ? 'pass' : 'fail', `「送る」→ 上の帯に「${chip.txt}」（表示=${chip.vis}）、画面「${chip.state}」。受け側のターミナル（${lines.length} 行）の例: ${lines.filter(([, l]) => /U1/.test(l)).slice(0, 2).map(([t, l]) => `[${t}s] ${l.slice(0, 150)}`).join(' ／ ')}`, '', [shotSend]);
// 17.3 play / pause / seek keep sending
const mark = lines.length;
await page.click('#play-btn'); await wait(3000);
const t1 = await page.evaluate(() => window.__editor.transport.now());
await page.click('#play-btn'); await wait(1500);
const afterPlay = lines.slice(mark);
await page.evaluate(() => window.__editor.transport.seek(17)); await wait(2500);
const afterSeek = lines.slice(mark).slice(afterPlay.length);
const rate = (ls) => ls.filter(([, l]) => /U1/.test(l)).map(([, l]) => Number((l.match(/U1\(Art-Net 0\): (\d+)/) ?? [])[1] ?? 0));
const rp = rate(afterPlay), rs = rate(afterSeek);
const headsPlay = afterPlay.map(([, l]) => (l.match(/最後はコマ (\d+)/) ?? [])[1]).filter(Boolean);
S.rec('17.3', rp.length >= 3 && rs.length >= 2 && rp.every((n) => n > 0) && rs.every((n) => n > 0) && new Set(headsPlay).size > 1 ? 'pass' : 'fail', `再生（時刻 12 → ${t1.toFixed(1)} 秒）中の受信 毎秒 ${rp.join(',')} 組、一時停止・移動（17 秒へ）のあとも毎秒 ${rs.join(',')} 組が届き続けた。再生中、受けたコマの番号が進んだ（記録のコマ ${[...new Set(headsPlay)].join('→')}）`);
// 17.4 stop
await page.click('#cx-btn'); await page.click('#cx-pop button[data-act="artnet"]'); await wait(400);
const markStop = lines.length;
await page.click('#an-stop'); await wait(3500);
const afterStop = lines.slice(markStop);
const chipAfter = await page.evaluate(() => !document.getElementById('an-chip').hidden);
const stopShot = await S.shot(page, '3-stopped');
await page.click('#an-close');
const zero = afterStop.filter(([, l]) => /受信なし/.test(l)).length;
S.rec('17.4', !chipAfter && zero >= 2 ? 'pass' : 'fail', `「止める」→ 上の帯の「Art-Net 送信中」は消えた（表示=${chipAfter}）、受け側は「受信なし」が ${zero} 秒続いた`, '', [stopShot]);
// 17.5 compare: wait for listener summary
const waitStart = Date.now();
while (exitCode === null && Date.now() - waitStart < 40000) await wait(500);
const summary = lines.map(([, l]) => l).filter((l) => /組が記録と一致$/.test(l)).at(-1) ?? '';
const m = summary.match(/(\d+)\/(\d+)/);
S.rec('17.5', m && Number(m[2]) > 100 && m[1] === m[2] && exitCode === 0 ? 'pass' : 'fail', `\`--compare\`：「${summary}」（受けた組すべてが、記録のコマと1バイトも違わない。終了コード ${exitCode}）。照合の途中の例: ${lines.filter(([, l]) => /照合/.test(l)).slice(-2).map(([, l]) => l.slice(-60)).join(' ／ ')}`);
S.rec('17.6', 'skip', '実際の機器・表示ソフトで受ける確認は、この環境では出来ない（機材も表示ソフトも無い）。未確認の本番として残す');
const newFiles = readdirSync(dir).filter((f) => !before.has(f));
for (const f of newFiles) unlinkSync(dir + f);
S.rec('17.後片付け', 'info', `書いた ${newFiles.join(',')} を消した`);
S.rec('17.コンソール', errors.length ? 'fail' : 'pass', errors.length ? errors.slice(0, 3).join(' | ') : 'コンソールのエラー 0');
S.save({ log: lines.slice(0, 60) });
child.kill();
await browser.close();
