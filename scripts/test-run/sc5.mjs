import { open, scenario, openPlayer, wait } from './lib.mjs';
const S = scenario(5, '音量を変えて聞く');
const { browser, page, errors } = await open({ w: 1024, h: 576 });
await openPlayer(page, 'show=hanabi&t=160');
await page.click('#go'); await wait(500);
await page.evaluate(() => window.__clock.pause());
await page.click('#vol-open');
const head = await page.textContent('#vol h4');
const rows = await page.$$eval('#vol label', (ls) => ls.map((l) => [l.firstChild.textContent, l.querySelector('input').min, l.querySelector('input').max, l.querySelector('output').value]));
const okRows = JSON.stringify(rows.map((r) => r[0])) === '["音楽","水音","花火"]' && rows.every((r) => r[1] === '0' && Number(r[2]) === 2 && r[3] === '100%');
S.rec('5.1-画面', head.includes('100% が基準') && okRows ? 'pass' : 'fail', `見出し「${head}」、スライダー ${rows.map((r) => `${r[0]} ${r[3]}（${r[1]}〜${Number(r[2]) * 100}%）`).join('・')}`, '', [await S.shot(page, 'menu-open')]);
const set = (name, v) => page.$eval(`#vol input[aria-label="${name}の音量"]`, (el, x) => { el.value = String(x); el.dispatchEvent(new Event('input')); }, v);
const gains = () => page.evaluate(() => ({ music: window.__clock.gainOf('music'), water: window.__clock.gainOf('water'), pyro: window.__clock.gainOf('pyro'), lv: ['music', 'water', 'pyro'].map((k) => window.__clock.level(k)) }));
const g0 = await gains();
await set('花火', 0); const g1 = await gains();
S.rec('5.1', g1.pyro === 0 && g1.music === g0.music && g1.water === g0.water ? 'pass' : 'fail', `花火 0%：花火の音の大きさ ${g0.pyro}→${g1.pyro}、音楽 ${g1.music}・水音 ${g1.water} は変わらない（機械で測った大きさ。耳で聞く確認は あなた）`);
await set('花火', 2); const g2 = await gains();
S.rec('5.2-値', Math.abs(g2.pyro - 2 * g0.pyro) < 1e-9 ? 'pass' : 'fail', `花火 200%：花火の音の大きさ ${g2.pyro}（100% の2倍）。足し算は最後のリミッターがかかる`);
await set('音楽', 0); const g3 = await gains();
S.rec('5.1-音楽', g3.music === 0 && g3.pyro === g2.pyro ? 'pass' : 'fail', `音楽 0%：音楽の大きさ ${g3.music}、花火 ${g3.pyro}・水音 ${g3.water} は残る`);
// splash button independent from levels
const before = await gains();
await page.keyboard.press('Escape'); await page.mouse.click(500, 200);
await page.click('#splash');
const after = await gains();
S.rec('5.水音ボタン', JSON.stringify(before.lv) === JSON.stringify(after.lv) ? 'pass' : 'fail', `「水音」ボタンを押しても 3つのスライダーの値は同じ（${after.lv.join(',')}）。ボタンの状態は別に持つ`);
await page.click('#splash');
await page.click('#vol-open'); await page.click('#vol-reset');
const g4 = await gains();
const vals = await page.$$eval('#vol input', (is) => is.map((i) => i.value));
S.rec('5.3', vals.join() === '1,1,1' && g4.pyro === g0.pyro && g4.music === g0.music ? 'pass' : 'fail', `「元に戻す」：スライダー ${vals.join(',')}、大きさ 音楽 ${g4.music}・水音 ${g4.water}・花火 ${g4.pyro}（初めと同じ）`, '', [await S.shot(page, 'after-reset')]);
await set('音楽', 0.5);
await page.reload();
await page.waitForFunction(() => !document.getElementById('go').disabled, null, { timeout: 90000 });
const kept = await page.$$eval('#vol input', (is) => is.map((i) => i.value));
S.rec('5.4', kept.join() === '0.5,1,1' ? 'pass' : 'fail', `音楽 50% にして再読み込み：スライダー ${kept.join(',')}`);
await page.evaluate(() => document.getElementById('start')?.remove());
await page.click('#vol-open'); await page.click('#vol-reset');
const vals2 = await page.$$eval('#vol input', (is) => is.map((i) => i.value));
S.rec('5.4-戻す', vals2.join() === '1,1,1' ? 'pass' : 'fail', `最後に「元に戻す」で 100% へ：${vals2.join(',')}（このテスト用の別プロフィールなので、あなたのブラウザの音量は変わっていない）`);
S.rec('5.1-聞く', 'user', '🔊 花火 0%／音楽 0% が、それぞれの音だけを消すか（耳で）');
S.rec('5.2', 'user', '🔊 花火 200% でも音が歪まないか（耳で）。この環境は音を出していないので聞けていない');
S.rec('5.5', 'user', '🔊 初めの 100% のバランスが花火版の最後でちょうどいいか（耳で）');
S.rec('5.コンソール', errors.length ? 'fail' : 'pass', errors.length ? errors.slice(0, 3).join(' | ') : 'コンソールのエラー 0');
S.save();
await browser.close();
